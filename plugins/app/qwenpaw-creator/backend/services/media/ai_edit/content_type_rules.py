def get_rules(content_type: str | None) -> dict:
    return CONTENT_TYPE_RULES.get(content_type or "general", CONTENT_TYPE_RULES["general"])


def build_criteria_block(content_type: str | None) -> str:
    rules = get_rules(content_type)
    parts = [
        rules["highlight_criteria"],
        rules["rhythm"],
        rules["avoid"],
    ]
    if rules.get("duration_constraint"):
        parts.append(rules["duration_constraint"])
    return "\n".join(parts)
